-- Initial schema for helpdesk-api (PostgreSQL). Applied by Flyway in the "docker" profile.
-- Column names follow Spring Boot's default naming (camelCase -> snake_case) and must match
-- the JPA entities; Hibernate runs with ddl-auto=validate and refuses to start on a mismatch.
-- Never edit this file after it has run: add V2__..., V3__... for later changes.

CREATE TABLE customers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255)                NOT NULL,
    email       VARCHAR(255)                NOT NULL UNIQUE,
    tier        VARCHAR(255)                NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE support_agents (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(255) NOT NULL,
    email  VARCHAR(255) NOT NULL UNIQUE,
    team   VARCHAR(255) NOT NULL
);

CREATE TABLE orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number     VARCHAR(255)                NOT NULL UNIQUE,
    customer_id      BIGINT                      NOT NULL REFERENCES customers (id),
    product_name     VARCHAR(255)                NOT NULL,
    amount           NUMERIC(12, 2)              NOT NULL,
    status           VARCHAR(255)                NOT NULL,
    tracking_number  VARCHAR(255),
    ordered_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE tickets (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  BIGINT                      NOT NULL REFERENCES customers (id),
    order_id     BIGINT                      REFERENCES orders (id),
    subject      VARCHAR(255)                NOT NULL,
    description  VARCHAR(4000)               NOT NULL,
    status       VARCHAR(255)                NOT NULL,
    priority     VARCHAR(255)                NOT NULL,
    category     VARCHAR(255),
    assignee_id  BIGINT                      REFERENCES support_agents (id),
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    sla_due_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    resolved_at  TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE ticket_comments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id      BIGINT                      NOT NULL REFERENCES tickets (id) ON DELETE CASCADE,
    author_type    VARCHAR(255)                NOT NULL,
    author_name    VARCHAR(255)                NOT NULL,
    body           VARCHAR(4000)               NOT NULL,
    internal_note  BOOLEAN                     NOT NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- Indexes for the queries the app actually runs (ticket queue filters, lookups by customer)
CREATE INDEX idx_orders_customer         ON orders (customer_id);
CREATE INDEX idx_tickets_customer        ON tickets (customer_id);
CREATE INDEX idx_tickets_status_sla      ON tickets (status, sla_due_at);
CREATE INDEX idx_tickets_assignee        ON tickets (assignee_id);
CREATE INDEX idx_ticket_comments_ticket  ON ticket_comments (ticket_id);
