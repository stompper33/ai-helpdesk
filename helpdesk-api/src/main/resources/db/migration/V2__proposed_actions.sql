-- Stage 5c: actions proposed by the AI agent, pending a human decision.
-- Matches com.helpdesk.domain.ProposedAction (Hibernate validates this at startup).

CREATE TABLE proposed_actions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id         BIGINT                      NOT NULL REFERENCES tickets (id),
    type              VARCHAR(255)                NOT NULL,
    status            VARCHAR(255)                NOT NULL,
    proposed_by       VARCHAR(255)                NOT NULL,
    reason            VARCHAR(1000),
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    decided_by_id     BIGINT                      REFERENCES support_agents (id),
    decided_at        TIMESTAMP(6) WITH TIME ZONE,
    decision_note     VARCHAR(1000),
    execution_result  VARCHAR(1000),
    version           BIGINT                      NOT NULL DEFAULT 0
);

-- the approval queue ("everything PENDING, oldest first") and the per-ticket list
CREATE INDEX idx_proposed_actions_status_created ON proposed_actions (status, created_at);
CREATE INDEX idx_proposed_actions_ticket         ON proposed_actions (ticket_id);
